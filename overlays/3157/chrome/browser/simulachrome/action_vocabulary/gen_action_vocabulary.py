"""Generates the C++ and JS action-vocabulary twins from action_vocabulary.json.

  C++ (build time, via GN action):
    gen_action_vocabulary.py --json X.json --cpp-out gen/.../action_vocabulary_generated.h
  TS (committed; the glic test client's manager prompt imports it):
    gen_action_vocabulary.py --json X.json --ts-out chrome/test/data/webui/glic/test_client/action_vocabulary.ts
  JS (committed; keep in sync):
    gen_action_vocabulary.py --json X.json --js-out resources/dashboard/agent/action_vocabulary.js
  CI / presubmit:
    gen_action_vocabulary.py --json X.json --js-out ... --check
    (exits 1 if the committed JS differs, and also verifies cross-references)
"""

import argparse
import json
import os
import sys

HEADER = 'Generated by gen_action_vocabulary.py from action_vocabulary.json. DO NOT EDIT.'


def _validate(v):
    errors = []
    canon = set(v['canonical_actions'])
    for alias, target in v['action_aliases'].items():
        if alias != alias.lower():
            errors.append('action alias not lowercase: %s' % alias)
        if target not in canon:
            errors.append('action alias %s -> unknown action %s' % (alias, target))
    cmd = v['command_aliases']
    for alias, target in cmd.items():
        if alias != alias.lower():
            errors.append('command alias not lowercase: %s' % alias)
        if target not in cmd.values():
            errors.append('command alias %s -> %s has no canonical entry' % (alias, target))
        if cmd.get(target) != target:
            errors.append('canonical command %s must map to itself' % target)
    seen = {}
    for op in v['planned_ops']:
        for name in [op['name']] + op.get('aliases', []):
            if name in seen and seen[name] != op['name']:
                errors.append('planned op name/alias %s used by %s and %s' %
                              (name, seen[name], op['name']))
            seen[name] = op['name']
        for slot in op.get('targets', []):
            if slot not in ('primary', 'from', 'to'):
                errors.append('op %s: unknown target slot %s' % (op['name'], slot))
    if errors:
        raise SystemExit('action_vocabulary.json invalid:\n  ' + '\n  '.join(errors))


def _cpp_str(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def _cpp_enum_name(op_name):
    return 'k' + ''.join(p.capitalize() for p in op_name.split('_'))


def gen_cpp(v):
    out = []
    w = out.append
    w('// %s' % HEADER)
    w('#ifndef CHROME_BROWSER_SIMULACHROME_ACTION_VOCABULARY_GENERATED_H_')
    w('#define CHROME_BROWSER_SIMULACHROME_ACTION_VOCABULARY_GENERATED_H_')
    w('')
    w('#include <array>')
    w('#include <cstddef>')
    w('#include <string_view>')
    w('')
    w('namespace simulachrome::vocabulary {')
    w('')
    w('struct AliasEntry {')
    w('  std::string_view alias;')
    w('  std::string_view canonical;')
    w('};')
    w('')

    def alias_table(name, mapping):
        items = sorted(mapping.items())
        w('inline constexpr std::array<AliasEntry, %d> %s = {{' % (len(items), name))
        for a, c in items:
            w('    {%s, %s},' % (_cpp_str(a), _cpp_str(c)))
        w('}};')
        w('')

    alias_table('kActionAliases', v['action_aliases'])
    alias_table('kCommandAliases', v['command_aliases'])

    w('inline constexpr std::array<std::string_view, %d> kCanonicalActions = {{' %
      len(v['canonical_actions']))
    for a in v['canonical_actions']:
        w('    %s,' % _cpp_str(a))
    w('}};')
    w('')

    ops = v['planned_ops']
    w('enum class PlannedOp {')
    for op in ops:
        w('  %s,' % _cpp_enum_name(op['name']))
    w('};')
    w('')
    w('struct PlannedOpSpec {')
    w('  PlannedOp op;')
    w('  std::string_view name;')
    w('  // Slots the embedded model must locate, in order. 0 = never asks it.')
    w('  int target_count;')
    w('  std::string_view target_slots[2];')
    w('};')
    w('')
    w('inline constexpr std::array<PlannedOpSpec, %d> kPlannedOps = {{' % len(ops))
    for op in ops:
        slots = op.get('targets', [])
        s0 = _cpp_str(slots[0]) if len(slots) > 0 else '""'
        s1 = _cpp_str(slots[1]) if len(slots) > 1 else '""'
        w('    {PlannedOp::%s, %s, %d, {%s, %s}},' %
          (_cpp_enum_name(op['name']), _cpp_str(op['name']), len(slots), s0, s1))
    w('}};')
    w('')
    pairs = []
    for op in ops:
        for name in [op['name']] + op.get('aliases', []):
            pairs.append((name, op['name']))
    pairs.sort()
    w('inline constexpr std::array<AliasEntry, %d> kPlannedOpNames = {{' % len(pairs))
    for a, c in pairs:
        w('    {%s, %s},' % (_cpp_str(a), _cpp_str(c)))
    w('}};')
    w('')
    w('// All lookups take an already-lowercased name and return the input when')
    w('// there is no alias, matching the previous hand-written behavior.')
    w('template <size_t N>')
    w('constexpr std::string_view LookupAlias(const std::array<AliasEntry, N>& t,')
    w('                                       std::string_view lower) {')
    w('  for (const AliasEntry& e : t) {')
    w('    if (e.alias == lower) {')
    w('      return e.canonical;')
    w('    }')
    w('  }')
    w('  return lower;')
    w('}')
    w('')
    w('constexpr std::string_view ResolveActionAlias(std::string_view lower) {')
    w('  return LookupAlias(kActionAliases, lower);')
    w('}')
    w('constexpr std::string_view ResolveCommandAlias(std::string_view lower) {')
    w('  return LookupAlias(kCommandAliases, lower);')
    w('}')
    w('constexpr std::string_view ResolvePlannedOpName(std::string_view lower) {')
    w('  return LookupAlias(kPlannedOpNames, lower);')
    w('}')
    w('')
    w('}  // namespace simulachrome::vocabulary')
    w('')
    w('#endif  // CHROME_BROWSER_SIMULACHROME_ACTION_VOCABULARY_GENERATED_H_')
    return '\n'.join(out) + '\n'


def _js_map(name, mapping):
    lines = ['export const %s = new Map([' % name]
    for a, c in sorted(mapping.items()):
        lines.append('  [%s, %s],' % (json.dumps(a), json.dumps(c)))
    lines.append(']);')
    return '\n'.join(lines)


def gen_js(v):
    pairs = {}
    for op in v['planned_ops']:
        for name in [op['name']] + op.get('aliases', []):
            pairs[name] = op['name']
    out = []
    w = out.append
    w('// %s' % HEADER)
    w('// Copyright 2026 The Chromium Authors')
    w('// Use of this source code is governed by a BSD-style license that can be')
    w('// found in the LICENSE file.')
    w('')
    w(_js_map('ACTION_ALIASES', v['action_aliases']))
    w('')
    w(_js_map('COMMAND_ALIASES', v['command_aliases']))
    w('')
    w(_js_map('PLANNED_OP_NAMES', pairs))
    w('')
    w('export const CANONICAL_ACTIONS = Object.freeze(%s);' % json.dumps(v['canonical_actions']))
    w('')
    w('export const PLANNED_OPS = Object.freeze(%s);' % json.dumps(
        [{'name': o['name'], 'targets': o.get('targets', []),
          'args': o.get('args', []), 'summary': o['summary']}
         for o in v['planned_ops']], indent=2))
    w('')
    w('function lookup(map, raw) {')
    w("  const lower = String(raw || '').trim().toLowerCase();")
    w('  return map.has(lower) ? map.get(lower) : lower;')
    w('}')
    w('')
    w('export function resolveActionAlias(raw) {')
    w('  return lookup(ACTION_ALIASES, raw);')
    w('}')
    w('export function resolveCommandAlias(raw) {')
    w('  return lookup(COMMAND_ALIASES, raw);')
    w('}')
    w('export function resolvePlannedOpName(raw) {')
    w('  return lookup(PLANNED_OP_NAMES, raw);')
    w('}')
    return '\n'.join(out) + '\n'


def gen_ts(v):
    pairs = {}
    for op in v['planned_ops']:
        for name in [op['name']] + op.get('aliases', []):
            pairs[name] = op['name']
    out = []
    w = out.append
    w('// %s' % HEADER)
    w('// Copyright 2026 The Chromium Authors')
    w('// Use of this source code is governed by a BSD-style license that can be')
    w('// found in the LICENSE file.')
    w('')
    w('export interface PlannedOpSpec {')
    w('  name: string;')
    w('  targets: string[];')
    w('  args: string[];')
    w('  summary: string;')
    w('}')
    w('')
    w('export const PLANNED_OPS: ReadonlyArray<PlannedOpSpec> = %s;' % json.dumps(
        [{'name': o['name'], 'targets': o.get('targets', []),
          'args': o.get('args', []), 'summary': o['summary']}
         for o in v['planned_ops']], indent=2))
    w('')
    w('export const PLANNED_OP_NAMES: ReadonlyMap<string, string> = new Map([')
    for a, c in sorted(pairs.items()):
        w('  [%s, %s],' % (json.dumps(a), json.dumps(c)))
    w(']);')
    w('')
    w('export function resolvePlannedOpName(raw: string): string {')
    w("  const lower = String(raw || '').trim().toLowerCase();")
    w('  return PLANNED_OP_NAMES.get(lower) ?? lower;')
    w('}')
    w('')
    w('// The op list shown to the manager model. Built from the same table the')
    w('// C++ validator uses, so the prompt can never offer an op that is rejected.')
    w('export function buildPlannedOpsPromptBlock(): string {')
    w('  return PLANNED_OPS')
    w('      .map((op) => {')
    w("        const target = op.targets.length ?")
    w("            op.targets.map((t) => (t === 'primary' ? 'target' : t)).join(' + ') :")
    w("            'no target';")
    w("        const args = op.args.length ? `; args: ${op.args.join(', ')}` : '';")
    w('        return `${op.name} (${target}${args}) - ${op.summary}`;')
    w('      })')
    w("      .join('\\n');")
    w('}')
    return '\n'.join(out) + '\n'


def _write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        f.write(text)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--json', required=True)
    p.add_argument('--cpp-out')
    p.add_argument('--js-out')
    p.add_argument('--ts-out')
    p.add_argument('--check', action='store_true',
                   help='fail if --js-out/--cpp-out on disk differ from generated')
    p.add_argument('--stamp', help='touch this file on success (for GN actions)')
    p.add_argument('--action-types-js',
                   help='types.js whose ACTION_TYPES values must equal canonical_actions')
    a = p.parse_args()
    with open(a.json) as f:
        v = json.load(f)
    _validate(v)
    rc = 0
    for path, text in ((a.cpp_out, gen_cpp(v) if a.cpp_out else None),
                       (a.js_out, gen_js(v) if a.js_out else None),
                       (a.ts_out, gen_ts(v) if a.ts_out else None)):
        if not path:
            continue
        if a.check:
            try:
                with open(path) as f:
                    on_disk = f.read()
            except OSError:
                on_disk = None
            if on_disk != text:
                sys.stderr.write('%s is stale: regenerate from action_vocabulary.json\n' % path)
                rc = 1
        else:
            _write(path, text)
    if a.action_types_js:
        import re
        with open(a.action_types_js) as f:
            src = f.read()
        start = src.index('export const ACTION_TYPES')
        end = src.index('};', start)
        js_actions = set(re.findall(r":\s*'([a-z_]+)'", src[start:end]))
        canon = set(v['canonical_actions'])
        if js_actions != canon:
            sys.stderr.write(
                'ACTION_TYPES in %s drifted from action_vocabulary.json: '
                'only in JS=%s only in vocabulary=%s\n' %
                (a.action_types_js, sorted(js_actions - canon),
                 sorted(canon - js_actions)))
            rc = 1
    if rc == 0 and a.stamp:
        _write(a.stamp, '')
    return rc


if __name__ == '__main__':
    sys.exit(main())
